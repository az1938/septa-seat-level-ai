export function glyphs(font: Record<string, string[]>, text: string): string[][] {
  return [...text.toUpperCase()].map((ch) => font[ch] ?? font[" "] ?? []);
}

/** Width in font pixels of `text` with `spacing` blank columns between glyphs. */
export function textWidth(font: Record<string, string[]>, text: string, spacing = 1): number {
  const g = glyphs(font, text);
  return g.reduce((w, b) => w + (b[0]?.length ?? 0), 0) + Math.max(0, g.length - 1) * spacing;
}
